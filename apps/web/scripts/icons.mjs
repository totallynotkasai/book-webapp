// Renders the placeholder app icons and splash screens (P1-MOB-01) from icons/book.svg: the web
// favicon and Apple touch icon, Android's adaptive and legacy launcher icons, and the splash
// screens. The outputs are committed; run `npm run icons -w @book/web` after changing the mark or
// the colour. Rendering uses Playwright's Chromium, which E2E already installs.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

// The placeholder brand seed (PLACEHOLDER_SEED in packages/tokens; OPEN-07 decides the real one).
const TEAL = '#00696B';
const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const res = join(app, 'android/app/src/main/res');

const mark = readFileSync(join(app, 'icons/book.svg'), 'utf8');
const paths = [...mark.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]);
if (paths.length === 0) throw new Error('icons/book.svg has no paths');

/** The mark in a 24-unit box, scaled about its centre: `size` is its share of the box. */
const book = (size, fill = '#ffffff') => {
	const offset = 12 - 12 * size;
	return `<g transform="translate(${offset} ${offset - 0.35 * size}) scale(${size})">${paths
		.map((d) => `<path fill="${fill}" d="${d}"/>`)
		.join('')}</g>`;
};

/** An SVG of the given shape: a full square, a rounded square or a circle of teal. */
function icon(shape, size) {
	const back = {
		square: `<rect width="24" height="24" fill="${TEAL}"/>`,
		rounded: `<rect x="1" y="1" width="22" height="22" rx="5" fill="${TEAL}"/>`,
		circle: `<circle cx="12" cy="12" r="11" fill="${TEAL}"/>`
	}[shape];
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${back}${book(size)}</svg>`;
}

function splash(width, height) {
	const side = Math.min(width, height) * 0.3;
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
<rect width="100%" height="100%" fill="${TEAL}"/>
<svg x="${(width - side) / 2}" y="${(height - side) / 2}" width="${side}" height="${side}" viewBox="0 0 24 24">${book(1)}</svg>
</svg>`;
}

/** An Android vector drawable of the white mark for a 108 dp adaptive-icon layer. */
function vector(comment) {
	// The mark fills about 52 of 108 dp, inside the 66 dp safe zone every launcher mask keeps.
	const scale = 52 / 24;
	const offset = (108 - 52) / 2;
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment} Generated by apps/web/scripts/icons.mjs from icons/book.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="${scale}"
        android:scaleY="${scale}"
        android:translateX="${offset}"
        android:translateY="${offset - 0.35 * scale}">
${paths.map((d) => `        <path android:fillColor="#FFFFFF" android:pathData="${d}" />`).join('\n')}
    </group>
</vector>
`;
}

function write(path, data) {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, data);
	console.log(`wrote ${path.slice(app.length + 1)}`);
}

// ---- Vectors: written directly ----
write(join(app, 'src/lib/assets/favicon.svg'), `${icon('rounded', 0.8)}\n`);
write(
	join(res, 'drawable/ic_launcher_foreground.xml'),
	vector('The adaptive icon’s foreground and monochrome (themed icon) layers.')
);

// ---- Bitmaps: rendered in Chromium ----
const browser = await chromium.launch();
const page = await browser.newPage();

async function png(svg, width, height, path, transparent = false) {
	await page.setViewportSize({ width, height });
	await page.setContent(
		`<style>html,body{margin:0;background:transparent}svg{display:block;width:${width}px;height:${height}px}</style>${svg}`
	);
	write(path, await page.screenshot({ omitBackground: transparent, type: 'png' }));
}

// iOS rounds the corners itself, so the touch icon is a full square.
await png(icon('square', 0.66), 180, 180, join(app, 'static/apple-touch-icon.png'));

const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [density, factor] of Object.entries(densities)) {
	// Legacy launcher icons for Android 7 (API 24–25); 8 and later use the adaptive icon.
	const px = 48 * factor;
	await png(icon('rounded', 0.72), px, px, join(res, `mipmap-${density}/ic_launcher.png`), true);
	await png(
		icon('circle', 0.66),
		px,
		px,
		join(res, `mipmap-${density}/ic_launcher_round.png`),
		true
	);
	// Splash screens before Android 12 (12 and later draw their own from the theme).
	const [w, h] = {
		mdpi: [320, 480],
		hdpi: [480, 800],
		xhdpi: [720, 1280],
		xxhdpi: [960, 1600],
		xxxhdpi: [1280, 1920]
	}[density];
	await png(splash(w, h), w, h, join(res, `drawable-port-${density}/splash.png`));
	await png(splash(h, w), h, w, join(res, `drawable-land-${density}/splash.png`));
}
await png(splash(480, 320), 480, 320, join(res, 'drawable/splash.png'));

await browser.close();
