import { generateTheme, PLACEHOLDER_SEED, tokensToCss } from './theme';

/**
 * The stylesheet `default-theme.css` is generated from: the placeholder seed at standard contrast,
 * light by default and dark when the device prefers it. It paints the app before any script runs;
 * the user's own theme then replaces it at runtime (`applyTheme`). Regenerate with `npx vitest -u`
 * (a test fails if the committed file and the generator ever disagree).
 */
export function defaultThemeCss(): string {
	const light = generateTheme({ seed: PLACEHOLDER_SEED, mode: 'light', contrast: 'standard' });
	const dark = generateTheme({ seed: PLACEHOLDER_SEED, mode: 'dark', contrast: 'standard' });
	return [
		'/* Generated by packages/tokens/src/default-theme.ts. Do not edit; run `npx vitest -u`. */',
		':root {',
		tokensToCss(light),
		'\tcolor-scheme: light;',
		'}',
		'',
		'@media (prefers-color-scheme: dark) {',
		'\t:root {',
		tokensToCss(dark, '\t\t'),
		'\t\tcolor-scheme: dark;',
		'\t}',
		'}',
		''
	].join('\n');
}
