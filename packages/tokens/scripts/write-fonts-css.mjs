// Writes src/fonts.css: @font-face rules for the self-hosted fonts (DESIGN.md §11.3), Latin and
// Latin Extended only, under plain family names ('Nunito', 'Literata', …) so the token stacks stay
// readable. The files come from Fontsource packages (SIL OFL), resolved from the repo's
// node_modules. Run after changing a font package: node packages/tokens/scripts/write-fonts-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const SUBSETS = ['latin-ext', 'latin'];

/** family: CSS family name; pkg; css files to read faces from; file stem per style. */
const FONTS = [
	{ family: 'Nunito', pkg: '@fontsource-variable/nunito', css: ['wght.css', 'wght-italic.css'] },
	{
		family: 'Literata',
		pkg: '@fontsource-variable/literata',
		css: ['wght.css', 'wght-italic.css']
	},
	{
		family: 'Source Serif 4',
		pkg: '@fontsource-variable/source-serif-4',
		css: ['wght.css', 'wght-italic.css']
	},
	{
		family: 'Merriweather',
		pkg: '@fontsource-variable/merriweather',
		css: ['wght.css', 'wght-italic.css']
	},
	{
		family: 'Atkinson Hyperlegible',
		pkg: '@fontsource/atkinson-hyperlegible',
		css: ['400.css', '400-italic.css', '700.css', '700-italic.css']
	},
	{
		family: 'OpenDyslexic',
		pkg: '@fontsource/opendyslexic',
		css: ['400.css', '400-italic.css', '700.css', '700-italic.css']
	}
];

const out = [
	'/*',
	' * Self-hosted fonts (DESIGN.md §11.3), all SIL OFL, from Fontsource packages. Latin and Latin',
	' * Extended only, to keep the app small. Generated by scripts/write-fonts-css.mjs; do not edit.',
	' * Arial Rounded MT is never here: it is commercial and used only when the device has it.',
	' */'
];

for (const font of FONTS) {
	for (const file of font.css) {
		const css = readFileSync(join(root, 'node_modules', font.pkg, file), 'utf8');
		for (const block of css.split('@font-face').slice(1)) {
			const src = /src: url\(\.\/files\/([^)]+)\)/.exec(block)?.[1];
			if (!src || !SUBSETS.some((s) => src.includes(`-${s}-`))) continue;
			const style = /font-style: (\w+)/.exec(block)?.[1];
			const weight = /font-weight: ([\d ]+);/.exec(block)?.[1];
			const range = /unicode-range: ([^;]+);/.exec(block)?.[1];
			const format = src.includes('-wght-') ? 'woff2-variations' : 'woff2';
			out.push(
				'',
				'@font-face {',
				`\tfont-family: '${font.family}';`,
				`\tfont-style: ${style};`,
				'\tfont-display: swap;',
				`\tfont-weight: ${weight};`,
				`\tsrc: url('../../../node_modules/${font.pkg}/files/${src}') format('${format}');`,
				// OpenDyslexic's Fontsource CSS gives no range: the face then covers every character.
				...(range ? [`\tunicode-range: ${range};`] : []),
				'}'
			);
		}
	}
}

writeFileSync(join(here, '..', 'src', 'fonts.css'), out.join('\n') + '\n');
console.log('Wrote src/fonts.css');
