function pathOf(file) {
	const svg = readFileSync(join(source, file), 'utf8');
	const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
	if (paths.length === 0) throw new Error(`No path in ${file}`);
	return paths.join(' ');
}

const entries = [];
for (const name of ICONS) {
	entries.push([name, pathOf(`${name}.svg`)]);
	if (FILLED.has(name)) entries.push([`${name}-fill`, pathOf(`${name}-fill.svg`)]);
}

